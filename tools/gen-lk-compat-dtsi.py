#!/usr/bin/env python3
"""Generate devicetree/mt6771-mtk-lk-compat.dtsi from the vendor dtbo overlay.

The Cosmo's MediaTek LK force-applies the `dtbo` partition overlay onto whatever
DTB is appended to the kernel, and ASSERTs (reboot loop) if that fails. The
overlay resolves ~60 vendor labels through the base DTB's /__symbols__. This
script reads the labels out of the decompiled overlay (__fixups__) and emits a
dtsi that satisfies LK without letting vendor content touch real mainline nodes.
See research/lk-dtb-requirements.md.

Usage: gen-lk-compat-dtsi.py <overlay.dts (dtc -I dtb -O dts of an overlay)> > out.dtsi
"""
import re, sys

src = open(sys.argv[1]).read()
fix = re.search(r'__fixups__ \{(.*?)\n\t\};', src, re.S).group(1)
labels = re.findall(r'^\s*([A-Za-z0-9_]+) = ', fix, re.M)

# Labels LK later looks up by *path* in the merged tree get vendor-shaped homes;
# everything else lands in an inert sink the kernel never populates.
SPECIAL = {
    'chosen': ('/chosen', None),
    'odm': ('/odm', None),
    'gpio': ('/gpio@10005000', None),
}
sink, syms, anchors = [], [], []
for l in labels:
    if l in SPECIAL:
        syms.append((l, SPECIAL[l][0])); anchors.append('lk_' + l); continue
    body = ''
    if l == 'scp':
        # platform_fdt_scp(): node must exist or LK asserts (mt_boot.c:0x394)
        body = '\n\t\t\tcompatible = "mediatek,scp";\n\t\t\tstatus = "disabled";\n\t\t'
    m = re.fullmatch(r'i2c(\d+)', l)
    if m:
        body = '\n\t\t\tid = <%s>;\n\t\t' % m.group(1)
    name = l.replace('_', '-')
    sink.append('\t\tlk_%s: %s {%s};' % (l, name, body))
    syms.append((l, '/mtk-lk-sink/' + name)); anchors.append('lk_' + l)

out = []
out.append('''// SPDX-License-Identifier: (GPL-2.0-only OR MIT)
/*
 * GENERATED by tools/gen-lk-compat-dtsi.py - do not edit by hand.
 *
 * MediaTek LK (Planet Cosmo, k71v1_64_bsp, 2020-07-06) compatibility layer.
 * Include this LAST from the board .dts. What LK demands of the appended DTB
 * (each one is an ASSERT or while(1) in LK when violated):
 *
 *  1. The vendor `dtbo` overlay must apply: /__symbols__ must resolve every
 *     label in the overlay's __fixups__, and each target needs a phandle.
 *  2. /chosen/bootargs must exist.
 *  3. A node with compatible "mediatek,scp" must exist.
 *  4. /reserved-memory must exist, and no child with a static `reg` may
 *     overlap a region LK reserved itself (ATF, TEE, SSPM, SPM, SCP, modem,
 *     framebuffer...). LK appends those as mblock-N-* nodes on its own.
 *  5. /memory and /chosen must exist (LK rewrites reg/bootargs/initrd).
 */

/ {
	reserved-memory {
		/* LK appends the real ones (mblock-N-*); static copies make it hang. */
		/delete-node/ atf@54600000;
		/delete-node/ spm@77ff0000;
		/delete-node/ sspm@7ff00000;
		/delete-node/ scp@9f900000;
		/delete-node/ dramc@bffff000;
		/delete-node/ tee@edb00000;
	};

	lk_chosen: chosen { };

	/* LK reads LED/backlight config from /odm/led@N (vendor overlay fills it) */
	lk_odm: odm { };

	/* LK applies gpio_init_default from here (vendor overlay fills it) */
	lk_gpio: gpio@10005000 {
		reg = <0 0x10005000 0 0x1000>;
	};

	/* No compatible: the kernel never creates devices at or below this node. */
	mtk-lk-sink {''')
out.append('\t\t/* forces dtc to emit a phandle for every overlay target */')
out.append('\t\tlk-phandle-anchors = <' + '\n\t\t\t'.join('&%s' % a for a in anchors) + '>;\n')
out += sink
out.append('\t};\n')
out.append('\t__symbols__ {')
out += ['\t\t%s = "%s";' % s for s in syms]
out.append('\t};\n};')
print('\n'.join(out))
