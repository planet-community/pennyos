#!/usr/bin/env python3
"""Generate devicetree/pennyos-battery.dtsi from the vendor battery profile.

The stock Android device tree (captured by tools/android-recon.sh as live.dts) carries
MediaTek's battery profile in /battery: battery0_profile_t0..t3 at 50, 25, 0 and -10 C,
each 100 triples of (discharged charge in 0.1 mAh, open-circuit voltage in 0.1 mV,
internal resistance in 0.1 mOhm).

PennyOS charges to 4.2 V (tools/rootfs/files/penny-charge-setup), not Android's 4.4 V,
so 100 % here is the charge at an open-circuit 4.2 V and 0 % the vendor's 3.4 V
shutdown voltage. Only the 25 C table is used: there is no battery temperature yet.

Usage: tools/gen-battery-dtsi.py collected/device-dumps/<dump>/live.dts > devicetree/pennyos-battery.dtsi
"""
import re
import sys

FULL_MV, EMPTY_MV = 4200, 3400
T_INDEX, T_CELSIUS = 1, 25          # battery0_profile_t1 is the 25 C table
METER_MOHM = 50                     # vendor FG_METER_RESISTANCE: board path to the cell

src = open(sys.argv[1]).read()
raw = re.search(r"battery0_profile_t%d = <([^>]*)>" % T_INDEX, src).group(1)
v = [int(x, 16) for x in raw.split()]
rows = [(v[i] / 10, v[i + 1] / 10, v[i + 2] / 10) for i in range(0, len(v), 3)]


def mah_at(mv):
    for a, b in zip(rows, rows[1:]):
        if a[1] >= mv >= b[1]:
            return a[0] + (b[0] - a[0]) * (a[1] - mv) / (a[1] - b[1])
    raise ValueError(mv)


def mv_at(mah):
    for a, b in zip(rows, rows[1:]):
        if a[0] <= mah <= b[0]:
            return a[1] + (b[1] - a[1]) * (mah - a[0]) / (b[0] - a[0])
    raise ValueError(mah)


q_full, q_empty = mah_at(FULL_MV), mah_at(EMPTY_MV)
usable = q_empty - q_full
r_mid = rows[len(rows) // 2][2]
table = []
for pct in range(100, -1, -5):
    table.append((round(mv_at(q_full + usable * (100 - pct) / 100) * 1000), pct))

print(f"""// SPDX-License-Identifier: (GPL-2.0-only OR MIT)
/*
 * The Cosmo's battery and its fuel gauge (kernel/drivers/cosmo_fg.c).
 *
 * GENERATED by tools/gen-battery-dtsi.py from the vendor battery profile in the stock
 * device tree ({T_CELSIUS} C table). 100 % is an open-circuit {FULL_MV / 1000:.1f} V, the voltage
 * PennyOS charges to; 0 % is the vendor's {EMPTY_MV / 1000:.1f} V shutdown voltage. Between
 * them the cell holds {usable:.0f} mAh. Internal resistance at half charge is
 * {r_mid:.0f} mOhm, plus {METER_MOHM} mOhm of board path to the voltage sense point.
 */
#include <dt-bindings/iio/adc/mediatek,mt6370_adc.h>

/ {{
	cosmo_battery: battery {{
		compatible = "simple-battery";
		device-chemistry = "lithium-ion";
		charge-full-design-microamp-hours = <{round(usable * 1000)}>;
		voltage-min-design-microvolt = <{EMPTY_MV * 1000}>;
		constant-charge-voltage-max-microvolt = <{FULL_MV * 1000}>;
		factory-internal-resistance-micro-ohms = <{round((r_mid + METER_MOHM) * 1000)}>;
		ocv-capacity-celsius = <{T_CELSIUS}>;
		ocv-capacity-table-0 = <""")
for uv, pct in table:
	print(f"\t\t\t{uv} {pct}")
print(f"""\t\t>;
	}};

	fuel-gauge {{
		compatible = "planet,cosmo-fuel-gauge";
		mediatek,pmic = <&pmic>;
		monitored-battery = <&cosmo_battery>;
		io-channels = <&mt6370_adc MT6370_CHAN_VBAT>;
		io-channel-names = "vbat";
	}};
}};""")
